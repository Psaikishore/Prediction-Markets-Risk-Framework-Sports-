"""Export every raw dataset (parquet / cached JSON) to CSV under data/csv for inspection.

The full trade tape is ~13M rows; it is written in full (kalshi_trades_full.csv) and also as a
100k-row sample plus a per-market summary so it can be opened in a spreadsheet.
"""

import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from pmrisk import DATA_RAW, ROOT

CSV = ROOT / "data" / "csv"


def main():
    CSV.mkdir(parents=True, exist_ok=True)
    written = []

    def out(df: pd.DataFrame, name: str, **kw):
        path = CSV / f"{name}.csv"
        df.to_csv(path, index=False, **kw)
        written.append((name, len(df), path.stat().st_size / 1e6))

    # nflverse
    sched = pd.read_parquet(DATA_RAW / "nflverse_schedules.parquet")
    out(sched, "nflverse_schedules")

    # Kalshi markets and events
    markets = pd.read_parquet(DATA_RAW / "kalshi_markets.parquet")
    out(markets, "kalshi_markets")
    out(pd.read_parquet(DATA_RAW / "kalshi_events.parquet"), "kalshi_events")

    # Kalshi trades: full, sample, per-market summary
    trades = pd.read_parquet(DATA_RAW / "kalshi_trades.parquet")
    trades = trades.merge(markets[["ticker", "kind", "event_ticker"]], on="ticker", how="left")
    cols = ["trade_id", "ticker", "event_ticker", "kind", "created_time", "yes_price", "no_price", "contracts",
            "taker_side", "taker_outcome_side", "taker_book_side", "is_block_trade"]
    trades = trades[[c for c in cols if c in trades.columns]].sort_values(["ticker", "created_time"])
    out(trades, "kalshi_trades_full")
    out(trades.sample(100_000, random_state=0).sort_values(["ticker", "created_time"]), "kalshi_trades_sample100k")
    per_market = trades.groupby(["ticker", "event_ticker", "kind"]).agg(
        n_trades=("contracts", "size"), contracts=("contracts", "sum"),
        first_trade=("created_time", "min"), last_trade=("created_time", "max"),
        first_price=("yes_price", "first"), last_price=("yes_price", "last"),
        vwap=("yes_price", lambda s: (s * trades.loc[s.index, "contracts"]).sum() / trades.loc[s.index, "contracts"].sum()),
    ).reset_index()
    for c in ("first_price", "last_price", "vwap"):
        per_market[c] = per_market[c].round(4)
    out(per_market, "kalshi_trades_per_market")

    # Kalshi hourly candlesticks
    candles = pd.read_parquet(DATA_RAW / "kalshi_candles.parquet")
    candles = candles.merge(markets[["ticker", "kind", "event_ticker"]], on="ticker", how="left")
    front = ["ticker", "event_ticker", "kind", "end_time"]
    candles = candles[front + [c for c in candles.columns if c not in front + ["end_ts"]]]
    out(candles.sort_values(["ticker", "end_time"]), "kalshi_candles_hourly")

    # Feature table
    f = DATA_RAW.parent / "processed" / "features" / "games_features.parquet"
    if f.exists():
        out(pd.read_parquet(f), "games_features")

    # Processed EDA tables already exist as CSV; copy them alongside for one-stop browsing.
    for f in sorted((ROOT / "data" / "processed").glob("*.csv")):
        df = pd.read_csv(f)
        out(df, f"eda_{f.stem}")

    readme = CSV / "README.md"
    lines = ["# CSV exports", "", "Generated by `scripts/export_csv.py` from the raw parquet/JSON pulls.", "",
             "| file | rows | MB |", "|---|---:|---:|"]
    lines += [f"| {n}.csv | {r:,} | {mb:.1f} |" for n, r, mb in written]
    lines += ["", "## Column notes", "",
              "**nflverse_schedules**: one row per game 2015–2026. `result` = home − away score, `total` = sum. "
              "`spread_line` is the closing spread as the home team's expected margin (positive = home favoured); "
              "`total_line`, `home_moneyline`/`away_moneyline` are closing consensus lines. Scores are NaN for unplayed games.", "",
              "**kalshi_markets**: one row per Kalshi contract. `kind` ∈ winner/spread/total. `floor_strike` is the strike "
              "(spread: team named in the ticker wins by more than this; total: combined points over this). `result` ∈ yes/no once settled.", "",
              "**kalshi_events**: one row per game-level event (e.g. `KXNFLGAME-26SEP28PHICHI` = PHI at CHI, 2026-09-28). "
              "Includes 2025-season events whose markets are archived and have no trades.", "",
              "**kalshi_trades_***: every trade on the exchange for these markets. `yes_price` in dollars (0–1), `contracts` = size "
              "($1 notional each at settlement), `taker_side` = which side the aggressor took. `_full` is the whole tape, "
              "`_sample100k` a random sample, `_per_market` one row per contract with counts, VWAP and first/last prices.", "",
              "**kalshi_candles_hourly**: one row per market per hour. `open/high/low/close/mean` are trade prices; "
              "`bid_*`/`ask_*` are the best yes bid/ask at the hour's open/close/high/low; `volume` contracts traded that hour; "
              "`open_interest` outstanding contracts at hour end. Needs API credentials to re-pull.", "",
              "**eda_***: summary tables produced by the EDA scripts (see reports/eda.md for what each shows)."]
    readme.write_text("\n".join(lines) + "\n")
    for n, r, mb in written:
        print(f"{n:<40} {r:>12,} rows {mb:8.1f} MB")


if __name__ == "__main__":
    main()
